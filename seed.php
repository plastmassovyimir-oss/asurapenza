<?php
// Демо-наполнение. Запуск из папки проекта: php seed.php
// Повторный запуск с ключом --force перезапишет все материалы.
require_once __DIR__ . '/lib.php';

if (php_sapi_name() !== 'cli') {
    exit('Запускайте из командной строки: php seed.php');
}
if (load_articles() && !in_array('--force', $argv, true)) {
    exit("Материалы уже есть. Чтобы перезаписать их, запустите: php seed.php --force\n");
}

$body = '<p>Это демонстрационный текст материала. В нём есть <b>жирный текст</b>, <i>курсив</i> и <a href="https://example.com" target="_blank">гиперссылка</a>.</p>'
      . '<h2>Подзаголовок внутри текста</h2>'
      . '<p>Второй абзац показывает, как выглядит основной текст статьи на сайте. Длинные материалы удобно делить подзаголовками.</p>'
      . '<blockquote>Цитата выделяется красной линией слева и курсивом.</blockquote>'
      . '<p>Заключительный абзац демо-материала.</p>';
$lead = 'Короткий подзаголовок (лид), который кратко пересказывает суть материала в одном-двух предложениях.';
$authors = ['Анна Смирнова', 'Игорь Петров', 'Мария Кузнецова', 'Олег Васильев'];

$now = time();
$articles = [];
$n = 0;

$make = function ($title, array $blocks, $minutesAgo) use (&$n, $now, $body, $lead, $authors) {
    $n++;
    return [
        'id'            => 'demo' . $n,
        'title'         => $title,
        'lead'          => $lead,
        'author'        => $authors[$n % count($authors)],
        'cover'         => 'https://picsum.photos/seed/asura' . $n . '/1200/800',
        'cover_caption' => 'Фото: демо',
        'body'          => $body,
        'blocks'        => $blocks,
        'published_at'  => $now - $minutesAgo * 60,
        'draft'         => false,
        'created_at'    => $now,
        'updated_at'    => $now,
    ];
};

$main = [
    'Пензенская Хунза: скрытый райский уголок на Земле',
    'Нефть и бензин: цены и решения',
    'Я выбрал свой путь',
    'В Спутнике построят ещё один детский сад',
];
foreach ($main as $i => $t) {
    $articles[] = $make($t, ['main', 'feed'], 15 + $i * 180);
}

$feed = [
    'Интервью с Кларой',
