    'Новые автобусные маршруты свяжут Арбеково и центр',
];
foreach ($feed as $i => $t) {
    $articles[] = $make($t, ['feed'], 40 + $i * 70);
}

$square = [
    'Город, который мы не замечаем: прогулка по старым дворам',
    'Почему пензенцы любят Суру: пять историй',
    'Заметки о жизни на окраине',
    'Старая Пенза на редких фотографиях',
];
foreach ($square as $i => $t) {
    $articles[] = $make($t, ['square'], 600 + $i * 1500);
}

$pov = [
    'POV: первый день в новой школе',
    'POV: ты фермер в сезон урожая',
    'POV: смена в городской скорой',
    'POV: открываешь кофейню в центре',
];
foreach ($pov as $i => $t) {
    $articles[] = $make($t, ['pov'], 900 + $i * 1400);
}

$opinion = [
    'Я выбрал свой путь, и вот почему',
    'Городу нужны не только дороги, но и тротуары',
    'Театр должен говорить со зрителем на равных',
];
foreach ($opinion as $i => $t) {
    $articles[] = $make($t, ['opinion'], 1200 + $i * 2000);
}

save_articles($articles);
echo 'Готово: создано ' . count($articles) . " демо-материалов.\n";